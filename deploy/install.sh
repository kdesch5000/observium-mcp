#!/usr/bin/env bash
# Install / upgrade observium-mcp as an HTTP service ON THE OBSERVIUM HOST.
#
#   sudo ./deploy/install.sh
#
# Idempotent. On first run it generates the bearer token and a DB password
# into /etc/observium-mcp/observium-mcp.env; later runs keep them.
#
# What it does:
#   1. system user `observium-mcp` (no shell, no home)
#   2. pinned uv + uv-managed Python under /opt/observium-mcp (immune to the
#      OS swapping /usr/bin/python3 during a release upgrade)
#   3. app copy + venv at /opt/observium-mcp/{app,venv}
#   4. read-only MariaDB account observium_mcp@localhost (SELECT on observium.*)
#   5. systemd unit, enabled and (re)started, /health checked
#   6. `tailscale serve` publishes 127.0.0.1:$PORT to the tailnet on :$TS_PORT
set -euo pipefail

PREFIX=/opt/observium-mcp
ETC=/etc/observium-mcp
ENV_FILE=$ETC/observium-mcp.env
SVC_USER=observium-mcp
UNIT=observium-mcp.service
UV_VERSION=0.11.28
PY_VERSION=3.13
PORT=${OBSERVIUM_MCP_PORT:-18765}
TS_PORT=${OBSERVIUM_MCP_TS_PORT:-8765}
DB_NAME=observium
DB_USER=observium_mcp
DB_SOCKET=${OBSERVIUM_DB_SOCKET:-/run/mysqld/mysqld.sock}
RRD_PATH=${OBSERVIUM_RRD_PATH:-/opt/observium/rrd}
SRC=$(cd "$(dirname "$0")/.." && pwd)

[[ $EUID -eq 0 ]] || { echo "run as root (sudo)" >&2; exit 1; }
for bin in rrdtool mariadb tailscale openssl curl sha256sum rsync; do
    command -v "$bin" >/dev/null || { echo "missing required command: $bin" >&2; exit 1; }
done
log() { printf '==> %s\n' "$*"; }

# 1. user ------------------------------------------------------------------
if ! id -u "$SVC_USER" >/dev/null 2>&1; then
    log "creating system user $SVC_USER"
    useradd --system --no-create-home --home-dir /nonexistent --shell /usr/sbin/nologin "$SVC_USER"
fi

# 2. uv (pinned, checksum-verified) ----------------------------------------
install -d -m 0755 "$PREFIX" "$PREFIX/bin"
if ! "$PREFIX/bin/uv" --version 2>/dev/null | grep -q " $UV_VERSION"; then
    case $(uname -m) in
        x86_64) triple=x86_64-unknown-linux-gnu ;;
        aarch64) triple=aarch64-unknown-linux-gnu ;;
        *) echo "unsupported arch $(uname -m)" >&2; exit 1 ;;
    esac
    log "installing uv $UV_VERSION ($triple)"
    tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
    base=https://github.com/astral-sh/uv/releases/download/$UV_VERSION/uv-$triple.tar.gz
    curl -fsSL -o "$tmp/uv.tgz" "$base"
    curl -fsSL -o "$tmp/uv.tgz.sha256" "$base.sha256"
    (cd "$tmp" && echo "$(awk '{print $1}' uv.tgz.sha256)  uv.tgz" | sha256sum -c --quiet)
    tar -xzf "$tmp/uv.tgz" -C "$tmp"
    install -m 0755 "$tmp/uv-$triple/uv" "$PREFIX/bin/uv"
fi
export UV_PYTHON_INSTALL_DIR=$PREFIX/python UV_CACHE_DIR=$PREFIX/cache UV_PYTHON_PREFERENCE=only-managed

# 3. app + venv --------------------------------------------------------------
log "copying app to $PREFIX/app"
rsync -a --delete --exclude .venv --exclude venv --exclude .env --exclude .git \
    --exclude tests --exclude '__pycache__' --exclude '*.egg-info' "$SRC/" "$PREFIX/app/"
log "building venv (Python $PY_VERSION, uv-managed)"
"$PREFIX/bin/uv" python install -q "$PY_VERSION"
"$PREFIX/bin/uv" venv -q --clear --python "$PY_VERSION" "$PREFIX/venv"
"$PREFIX/bin/uv" pip install -q --compile-bytecode --python "$PREFIX/venv/bin/python" "$PREFIX/app"
chown -R root:root "$PREFIX"; chmod -R go-w "$PREFIX"

# 4. secrets + DB account ------------------------------------------------------
install -d -m 0750 -o root -g "$SVC_USER" "$ETC"
if [[ ! -f $ENV_FILE ]]; then
    log "generating $ENV_FILE (new token + DB password)"
    ts_json=$(tailscale status --json)
    ts_name=$(printf '%s' "$ts_json" | "$PREFIX/venv/bin/python" -c \
        'import json,sys;print(json.load(sys.stdin)["Self"]["DNSName"].rstrip("."))')
    ts_ip=$(tailscale ip -4 | head -1)
    umask 077
    cat >"$ENV_FILE" <<EOF
# observium-mcp service config (generated by deploy/install.sh)
OBSERVIUM_MCP_TRANSPORT=http
OBSERVIUM_MCP_HOST=127.0.0.1
OBSERVIUM_MCP_PORT=$PORT
OBSERVIUM_MCP_TOKEN=$(openssl rand -hex 32)
# Host headers accepted on /mcp (DNS-rebinding protection)
OBSERVIUM_MCP_ALLOWED_HOSTS=$ts_name:$TS_PORT,$ts_ip:$TS_PORT,127.0.0.1:*,localhost:*
OBSERVIUM_DB_SOCKET=$DB_SOCKET
OBSERVIUM_DB_NAME=$DB_NAME
OBSERVIUM_DB_USER=$DB_USER
OBSERVIUM_DB_PASS=$(openssl rand -hex 24)
OBSERVIUM_RRD_PATH=$RRD_PATH
EOF
fi
chown root:"$SVC_USER" "$ENV_FILE"; chmod 0640 "$ENV_FILE"

db_pass=$(sed -n 's/^OBSERVIUM_DB_PASS=//p' "$ENV_FILE")
[[ $db_pass =~ ^[0-9a-f]+$ ]] || { echo "OBSERVIUM_DB_PASS in $ENV_FILE must be hex" >&2; exit 1; }
log "ensuring read-only DB account $DB_USER@localhost"
mariadb <<SQL
CREATE USER IF NOT EXISTS '$DB_USER'@'localhost' IDENTIFIED BY '$db_pass';
ALTER USER '$DB_USER'@'localhost' IDENTIFIED BY '$db_pass';
GRANT SELECT ON \`$DB_NAME\`.* TO '$DB_USER'@'localhost';
FLUSH PRIVILEGES;
SQL

# 5. systemd -------------------------------------------------------------------
log "installing $UNIT"
install -m 0644 "$SRC/deploy/$UNIT" "/etc/systemd/system/$UNIT"
systemctl daemon-reload
systemctl enable -q "$UNIT"
systemctl restart "$UNIT"
for _ in $(seq 1 20); do
    curl -fsS "http://127.0.0.1:$PORT/health" >/dev/null 2>&1 && break
    sleep 0.5
done
log "health: $(curl -sS "http://127.0.0.1:$PORT/health" || echo FAILED)"

# 6. tailnet publish -------------------------------------------------------------
log "publishing to tailnet: :$TS_PORT -> 127.0.0.1:$PORT"
tailscale serve --bg --http="$TS_PORT" "http://127.0.0.1:$PORT" >/dev/null
tailscale serve status

cat <<EOF

Done. Register on each client (token: sudo grep TOKEN $ENV_FILE):
  claude mcp add --scope user --transport http observium \\
    http://$(tailscale status --json | "$PREFIX/venv/bin/python" -c \
      'import json,sys;print(json.load(sys.stdin)["Self"]["DNSName"].rstrip("."))'):$TS_PORT/mcp \\
    --header "Authorization: Bearer <token>"
EOF
